const dictionaries: Record<Lang, Dict> = { nl, en, fr, es };

interface Ctx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
}

const LangCtx = createContext<Ctx | null>(null);

const STORAGE_KEY = "werkkompas-lang";

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("nl");

  useEffect(() => {
    try {
      const stored = localStorage.getItem(STORAGE_KEY) as Lang | null;
      if (stored && (["nl", "en", "fr", "es"] as Lang[]).includes(stored)) {
        setLangState(stored);
        document.documentElement.lang = LOCALES[stored];
      }
    } catch {
      /* ignore */
    }
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
    if (typeof document !== "undefined") {
      document.documentElement.lang = LOCALES[l];
    }
  }, []);

  const t = useCallback(
    (key: string, params?: Record<string, string | number>) => {
      const dict = dictionaries[lang];
      let value = dict[key] ?? nl[key] ?? key;
      if (params) {
        for (const [k, v] of Object.entries(params)) {
          value = value.replace(`{${k}}`, String(v));
        }
      }
      return value;
    },
    [lang]
  );

  const value = useMemo<Ctx>(() => ({ lang, setLang, t }), [lang, setLang, t]);

  return <LangCtx.Provider value={value}>{children}</LangCtx.Provider>;
}

export function useT() {
  const ctx = useContext(LangCtx);
  if (!ctx) throw new Error("useT must be used inside LanguageProvider");
  return ctx;
}

export function useLocalized() {
  const { lang } = useT();
  const lm = useCallback((m: Mission) => localizeMission(m, lang), [lang]);
  const lc = useCallback((c: Certification) => localizeCert(c, lang), [lang]);
  return { mission: lm, cert: lc };
}

// ----- Locale-aware formatters -----

const SHORT_DAY_KEYS = ["day_short_Zo", "day_short_Ma", "day_short_Di", "day_short_Wo", "day_short_Do", "day_short_Vr", "day_short_Za"];
const LONG_DAY_KEYS = ["day_long_Zo", "day_long_Ma", "day_long_Di", "day_long_Wo", "day_long_Do", "day_long_Vr", "day_long_Za"];

export function useFormat() {
  const { lang, t } = useT();
  const locale = LOCALES[lang];

  const time = (iso: string) => {
    const d = new Date(iso);
    const h = d.getHours().toString().padStart(2, "0");
    const m = d.getMinutes().toString().padStart(2, "0");
    return `${h}:${m}`;
  };

  const timeRange = (a: string, b: string) => `${time(a)}–${time(b)}`;

  const dayLong = (iso: string) => {
    const d = new Date(iso);
    const day = t(LONG_DAY_KEYS[d.getDay()]);
    const month = new Date(iso).toLocaleString(locale, { month: "long" });
    return `${day} ${d.getDate()} ${month}`;
  };

  const dayShort = (iso: string) => {
    const d = new Date(iso);
    const day = t(SHORT_DAY_KEYS[d.getDay()]);
    const month = new Date(iso).toLocaleString(locale, { month: "short" }).replace(/\./g, "");
    return `${day} ${d.getDate()} ${month}`;
  };

  const monthShort = (iso: string) =>
    new Date(iso).toLocaleString(locale, { month: "short" }).replace(/\./g, "");

  const dateOnly = (iso: string) => {
    const d = new Date(iso);
    return `${d.getDate()} ${monthShort(iso)}`;
  };

  const euro = (n: number) =>
    new Intl.NumberFormat(locale, {
      style: "currency",
      currency: "EUR",
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    }).format(n);

  const euroShort = (n: number) => euro(n).replace(/[,.]00\b/, "");

  const hours = (h: number) => {
    const rounded = Math.round(h * 10) / 10;
    const num = lang === "en" ? rounded.toFixed(1) : rounded.toString().replace(".", ",");
    return `${num} ${t("hours_unit")}`;
  };

  const relativeFrom = (iso: string, nowISO: string) => {
    const diffMs = new Date(iso).getTime() - new Date(nowISO).getTime();
    const diffDays = Math.round(diffMs / (1000 * 60 * 60 * 24));
    if (diffDays === 0) return t("t_today");
    if (diffDays === 1) return t("t_tomorrow");
    if (diffDays === -1) return t("t_yesterday");
    if (diffDays > 1 && diffDays < 7) return t("t_in_days", { n: diffDays });
    if (diffDays < -1 && diffDays > -7) return t("t_days_ago", { n: Math.abs(diffDays) });
    return dateOnly(iso);
  };

  const timeAgo = (iso: string, nowISO: string) => {
    const diff = new Date(nowISO).getTime() - new Date(iso).getTime();
    const minutes = Math.floor(diff / 60000);
    if (minutes < 1) return t("t_just_now");
    if (minutes < 60) return t("t_min", { n: minutes });
    const hrs = Math.floor(minutes / 60);
    if (hrs < 24) return t("t_hours", { n: hrs });
    const days = Math.floor(hrs / 24);
    if (days < 7) return t("t_days_short", { n: days });
    return dateOnly(iso);
  };

  return {
    locale,
    time,
    timeRange,
    dayLong,
    dayShort,
    monthShort,
    dateOnly,
    euro,
    euroShort,
    hours,
    relativeFrom,
    timeAgo,
  };
}
